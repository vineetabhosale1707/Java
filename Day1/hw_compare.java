public class hw_compare {
    public static void main(String[] args) {
        int age1 = 57;
        int age2 = 64;

        System.out.println("age1 == age2 :" + (age1 == age2));
        System.out.println("age1 > age2 :" + (age1>age2));
        System.out.println("age1 < age2 :" + (age1<age2));
        System.out.println("age1 >= age2 :" + (age1>=age2));
        System.out.println("age1 <= age2 :" + (age1<=age2));
        System.out.println("age1!= age2 : " + (age1 != age2));


    }
}
